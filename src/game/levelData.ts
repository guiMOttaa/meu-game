function rectToSightSegments(x: number, y: number, w: number, h: number, id?: string): Segment[] {
  return [
    { x1: x, y1: y, x2: x + w, y2: y, id },
    { x1: x + w, y1: y, x2: x + w, y2: y + h, id },
    { x1: x + w, y1: y + h, x2: x, y2: y + h, id },
    { x1: x, y1: y + h, x2: x, y2: y, id },
  ];
}

